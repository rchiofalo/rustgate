//! `emit-schema` — emit a JSON Schema describing the `rustgate.toml`
//! configuration file.
//!
//! The schema is generated from the [`crate::cli::ConfigFile`] type via
//! `schemars::schema_for!`. Operators feed the output into editor
//! extensions (e.g. VS Code "Even Better TOML", IntelliJ TOML / Helix
//! LSPs) that consume JSON Schema for autocomplete and inline
//! validation when editing `rustgate.toml`.
//!
//! # Output contract
//!
//! The output is a single JSON document on stdout, pretty-printed with
//! `serde_json::to_string_pretty` for diff-friendliness. The committed
//! `schemas/rustgate-vX.Y.json` is regenerated by redirecting this
//! subcommand's output into the file:
//!
//! ```text
//! rustgate emit-schema > schemas/rustgate-v0.8.json
//! ```
//!
//! A regression test (`schema_export.rs`) re-runs the same generator at
//! test time and asserts the checked-in file matches byte-for-byte, so
//! a forgotten regen surfaces in CI rather than in operator runtime.
//!
//! # Stability
//!
//! The schema's *shape* (keys present, types, kebab-case rename) tracks
//! the [`crate::cli::ConfigFile`] mirror — adding a new TOML key adds a
//! property here automatically because `JsonSchema` is derived on the
//! macro-generated struct. The exact JSON document is *not* a public
//! contract: a new schemars release may reorder keys or refine type
//! expressions. Operators consuming this file in their editor settings
//! should pin the version-tagged path (`schemas/rustgate-v0.8.json`)
//! they reference rather than tracking `main` directly.
//!
//! Addresses #815 F-137.

use anyhow::{Context as _, Result};

use crate::cli::ConfigFile;

/// Entry point wired from `main.rs`. Writes the JSON Schema for
/// [`ConfigFile`] to stdout.
pub(crate) fn run() -> Result<()> {
    let json = build_schema_json()?;
    print!("{json}");
    Ok(())
}

/// Render the JSON Schema as a pretty-printed string. Extracted from
/// [`run`] so unit and integration tests can inspect the output
/// byte-for-byte without capturing stdout.
pub(crate) fn build_schema_json() -> Result<String> {
    let schema = schemars::schema_for!(ConfigFile);
    serde_json::to_string_pretty(&schema).context("serialize JSON Schema")
}

#[cfg(test)]
mod tests {
    #![allow(clippy::panic, clippy::unwrap_used)]

    use super::*;

    #[test]
    fn schema_is_pretty_printed_json() {
        let schema = build_schema_json().expect("build schema");
        // Pretty-printed JSON has at least one newline between top-level
        // properties and is non-empty.
        assert!(!schema.is_empty(), "schema must not be empty");
        assert!(
            schema.contains('\n'),
            "schema should be pretty-printed (multi-line)"
        );
    }

    #[test]
    fn schema_parses_as_valid_json() {
        let schema = build_schema_json().expect("build schema");
        let parsed: serde_json::Value =
            serde_json::from_str(&schema).expect("schema must parse as JSON");
        assert!(parsed.is_object(), "schema root must be a JSON object");
    }

    #[test]
    fn schema_advertises_jsonschema_dialect() {
        // schemars 0.9 emits a `$schema` URI identifying the JSON
        // Schema dialect (currently 2020-12). Editors use this URI to
        // select the right validator.
        let schema = build_schema_json().expect("build schema");
        let parsed: serde_json::Value = serde_json::from_str(&schema).expect("parse");
        assert!(
            parsed.get("$schema").is_some(),
            "schema must declare its `$schema` dialect URI"
        );
    }

    #[test]
    fn schema_describes_an_object_with_properties() {
        // The top-level type must be `object` and must expose a
        // `properties` map — that's what editor extensions key off to
        // produce key-completion lists.
        let schema = build_schema_json().expect("build schema");
        let parsed: serde_json::Value = serde_json::from_str(&schema).expect("parse");
        assert!(
            parsed.get("properties").is_some(),
            "schema must expose a `properties` map for editor autocomplete"
        );
    }

    #[test]
    fn schema_includes_kebab_case_keys() {
        // `ConfigFile` has `#[serde(rename_all = "kebab-case")]` so the
        // emitted property keys must match the TOML spelling, not the
        // Rust field names.
        let schema = build_schema_json().expect("build schema");
        let parsed: serde_json::Value = serde_json::from_str(&schema).expect("parse");
        let props = parsed
            .get("properties")
            .and_then(|p| p.as_object())
            .expect("properties is an object");
        // `tls-min-version` (kebab) must be present; the underscore
        // spelling `tls_min_version` must not — that would mean the
        // kebab rename did not propagate through schemars, breaking
        // every TOML editor that consumes the schema.
        assert!(
            props.contains_key("tls-min-version"),
            "kebab-case key `tls-min-version` missing from schema properties"
        );
        assert!(
            !props.contains_key("tls_min_version"),
            "snake_case key `tls_min_version` leaked into schema — kebab-case rename did not propagate"
        );
    }
}
