// ── 7. Rename obsolete keys ─────────────────────────────────────────────

#[test]
#[serial]
fn migrate_config_renames_obsolete_keys() {
    let input = "tls_cert = \"a.pem\"\ntls_key = \"k.pem\"\ntls_ca = \"ca.pem\"\n";
    let f = write_temp_toml(input);
    let out = Command::new(rustgate_bin())
        .args(["migrate-config", f.path().to_str().unwrap()])
        .output()
        .expect("spawn");
    assert!(
        out.status.success(),
        "stderr={}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    // All three legacy spellings replaced by the current ones.
    assert!(stdout.contains("cert = \"a.pem\""), "stdout: {stdout}");
    assert!(stdout.contains("key = \"k.pem\""), "stdout: {stdout}");
    assert!(stdout.contains("ca = \"ca.pem\""), "stdout: {stdout}");
    for legacy in ["tls_cert", "tls_key", "tls_ca"] {
        assert!(
            !stdout.contains(legacy),
            "obsolete key `{legacy}` leaked into output: {stdout}"
        );
    }
}

// ── 8. Warning emitted for dropped key ──────────────────────────────────

#[test]
#[serial]
fn migrate_config_logs_warning_for_dropped_keys() {
    // Drop case: `legacy_xml_strict` has no equivalent in v0.8 and
    // must trigger a warn-level event on stderr so an operator
    // running the subcommand from CI sees the diagnostic.
    let input = "tls_cert = \"a.pem\"\nlegacy_xml_strict = true\n";
    let f = write_temp_toml(input);
    let out = Command::new(rustgate_bin())
        .args(["migrate-config", f.path().to_str().unwrap()])
        .output()
        .expect("spawn");
    assert!(
        out.status.success(),
        "stderr={}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        !stdout.contains("legacy_xml_strict"),
        "dropped key leaked into stdout: {stdout}"
    );
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(
        stderr.contains("legacy_xml_strict") && stderr.contains("dropping obsolete config key"),
        "expected warn-level event for dropped key in stderr, got: {stderr}"
    );
}

// ── 9. Round trip through validate-config ───────────────────────────────

#[test]
#[serial]
fn migrate_config_round_trips_through_validate_config() {
    // Migrate a pre-v0.8 config, then point the existing
    // `validate-config` subcommand at the output. The whole point of
    // the migration framework is that the rewritten file parses
    // cleanly through the typed `ConfigFile` deserializer (which
    // would have rejected the pre-v0.8 keys at `deny_unknown_fields`).
    let dir = tempfile::tempdir().expect("tmpdir");
    let cert = dir.path().join("cert.pem");
    let key = dir.path().join("key.pem");
    let ca = dir.path().join("ca.pem");
    for p in [&cert, &key, &ca] {
        std::fs::write(p, "").expect("write tls material");
    }
    let input = format!(
        "tls_cert = \"{}\"
tls_key = \"{}\"
tls_ca = \"{}\"
",
        cert.display(),
        key.display(),
        ca.display(),
    );
    let input_path = dir.path().join("legacy.toml");
    let migrated_path = dir.path().join("migrated.toml");
    std::fs::write(&input_path, input).expect("write input");

    // Step 1: migrate.
    let migrate = Command::new(rustgate_bin())
        .args([
            "migrate-config",
            input_path.to_str().unwrap(),
            "--output",
            migrated_path.to_str().unwrap(),
        ])
        .output()
        .expect("spawn migrate");
    assert!(
        migrate.status.success(),
        "migrate-config failed: stderr={}",
        String::from_utf8_lossy(&migrate.stderr)
    );

    // Step 2: validate the migrated output.
    let validate = Command::new(rustgate_bin())
        .args([
            "--config",
            migrated_path.to_str().unwrap(),
            "validate-config",
        ])
        .env_remove("RUSTGATE_CERT")
        .env_remove("RUSTGATE_KEY")
        .env_remove("RUSTGATE_CA")
        .output()
        .expect("spawn validate");
    assert!(
        validate.status.success(),
        "validate-config rejected migrated output: stderr={}",
        String::from_utf8_lossy(&validate.stderr)
    );
    assert!(
        String::from_utf8_lossy(&validate.stdout).contains("valid"),
        "validate-config did not print 'valid': stdout={}",
        String::from_utf8_lossy(&validate.stdout)
    );
}

// ── 10. Comment preservation ────────────────────────────────────────────

#[test]
#[serial]
fn migrate_config_preserves_comments_when_possible() {
    // The whole reason we depend on `toml_edit` instead of the
    // round-trip-through-`toml::Value` shape is to keep the
    // operator's hand-written comments intact through a migration.
    // A comment that sat above a renamed key should ride along to
    // the new key; a comment unrelated to a rename should be
    // unchanged.
    let input = "# Operator note: this is the production cert\n\
                 tls_cert = \"prod.pem\"\n\
                 # Unrelated annotation\n\
                 bind = \"0.0.0.0:4433\"\n";
    let f = write_temp_toml(input);
    let out = Command::new(rustgate_bin())
        .args([
            "migrate-config",
            f.path().to_str().unwrap(),
            "--from",
            "pre-0.8",
        ])
        .output()
        .expect("spawn");
    assert!(
        out.status.success(),
        "stderr={}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.contains("Operator note"),
        "operator's comment lost during migration: {stdout}"
    );
    assert!(
        stdout.contains("Unrelated annotation"),
        "unrelated comment lost during migration: {stdout}"
    );
    assert!(
        stdout.contains("bind = \"0.0.0.0:4433\""),
        "unrelated key disappeared: {stdout}"
    );
}
