#![allow(clippy::panic, clippy::unwrap_used)]

//! Integration tests for the `migrate-config` subcommand (issue #815,
//! F-138). Each test spawns the rustgate binary as a subprocess and
//! checks the operator-facing contract: stdout vs. file output, the
//! `--from` flag overriding the in-file `# rustgate-version` comment,
//! the typed error variants, the warning-on-drop semantics, and the
//! end-to-end `migrate-config | validate-config` round trip.
//!
//! The subcommand itself is a pure file rewriter — it never opens a
//! listener and never validates the migrated TOML. The
//! `migrate_config_round_trips_through_validate_config` test is what
//! pins the integration with the existing `validate-config` story
//! (#1244).

use std::io::Write;
use std::process::Command;

use serial_test::serial;

/// Path to the built binary. Cargo sets `CARGO_BIN_EXE_rustgate` for
/// integration tests when the crate has a `[[bin]]` target.
fn rustgate_bin() -> String {
    env!("CARGO_BIN_EXE_rustgate").to_string()
}

/// Write `contents` to a fresh `.toml` file in a per-test tempdir.
/// Returns the [`tempfile::NamedTempFile`] so the caller's `path()`
/// stays valid for the duration of the test.
fn write_temp_toml(contents: &str) -> tempfile::NamedTempFile {
    let mut f = tempfile::Builder::new()
        .suffix(".toml")
        .tempfile()
        .expect("create temp toml");
    f.write_all(contents.as_bytes()).expect("write toml");
    f.flush().expect("flush toml");
    f
}

// ── 1. Round-trip on already-current config ────────────────────────────

#[test]
#[serial]
fn migrate_config_with_no_obsolete_keys_returns_input_unchanged() {
    let input = "cert = \"a.pem\"\nkey = \"k.pem\"\nca = \"ca.pem\"\n";
    let f = write_temp_toml(input);
    let out = Command::new(rustgate_bin())
        .args(["migrate-config", f.path().to_str().unwrap()])
        .output()
        .expect("spawn");
    assert!(
        out.status.success(),
        "migrate-config failed: stderr={}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    // The three keys all survive verbatim with their original values.
    assert!(stdout.contains("cert = \"a.pem\""), "stdout: {stdout}");
    assert!(stdout.contains("key = \"k.pem\""), "stdout: {stdout}");
    assert!(stdout.contains("ca = \"ca.pem\""), "stdout: {stdout}");
    // The banner is added even on the no-op path so a downstream
    // tool can confirm the chain ran.
    assert!(stdout.contains("# Generated by rustgate migrate-config from"));
}

// ── 2. File output ──────────────────────────────────────────────────────

#[test]
#[serial]
fn migrate_config_writes_to_output_path_when_specified() {
    let dir = tempfile::tempdir().expect("tmpdir");
    let input_path = dir.path().join("input.toml");
    let output_path = dir.path().join("output.toml");
    std::fs::write(&input_path, "tls_cert = \"a.pem\"\n").expect("write input");

    let out = Command::new(rustgate_bin())
        .args([
            "migrate-config",
            input_path.to_str().unwrap(),
            "--output",
            output_path.to_str().unwrap(),
            "--from",
            "pre-0.8",
        ])
        .output()
        .expect("spawn");
    assert!(
        out.status.success(),
        "migrate-config failed: stderr={}",
        String::from_utf8_lossy(&out.stderr)
    );
    // Stdout is empty when --output is set.
    assert!(
        out.stdout.is_empty(),
        "expected empty stdout when --output is set, got: {}",
        String::from_utf8_lossy(&out.stdout)
    );

    let written = std::fs::read_to_string(&output_path).expect("read output");
    assert!(written.contains("cert = \"a.pem\""));
    assert!(!written.contains("tls_cert"));
}

