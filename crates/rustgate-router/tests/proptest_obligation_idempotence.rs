#![allow(clippy::panic, clippy::unwrap_used)]
//! Property-based tests for the obligation dispatcher's composition
//! invariants (refs #787, F-22).
//!
//! The data-plane obligation actuator
//! [`rustgate_router::obligations::apply_obligations`] is documented
//! to satisfy three load-bearing invariants over the set of known
//! [`rustgate_authz::Obligation`] variants:
//!
//! 1. **Idempotence** — applying the same obligation set twice produces
//!    the same post-PEP payload as applying it once. Without this, a
//!    drain that re-runs obligation application on a stored copy could
//!    drift the payload further on each retry.
//! 2. **Order independence** — two permutations of the same obligation
//!    set produce byte-identical post-PEP output. The dispatcher
//!    enforces this via a stable sort on
//!    [`rustgate_authz::Obligation::chain_sort_key`] before actuation
//!    (refs #882).
//! 3. **Composition equivalence** — applying `A` then `B` separately
//!    produces the same payload as applying `A ∪ B` in one shot. This
//!    is the property the docstring on `apply_obligations` makes
//!    explicit ("`MaskPayload over MaskPoint = empty body; either order
//!    works`") and is the gate the per-recipient fan-out and the
//!    store-forward drain both rely on so they can stack Send and
//!    Receive obligations without re-deriving the canonical chaining
//!    order at every call site.
//!
//! These three properties are the pre-condition for trusting any callsite
//! that splits obligation application across multiple invocations: the
//! per-recipient fan-out in `Router::route_for_egress`, the
//! `filter_offline_messages` drain path that stacks Send-then-Receive
//! obligations, and the egress bridges that re-apply obligations on the
//! local copy. A regression that broke any of them would manifest as a
//! drained or fanned-out payload that diverged from the same-set
//! one-shot reference.
//!
//! The proptests exercise the four known [`Obligation`] variants today
//! (`MaskPoint`, `MaskPayload`, `TagClassified`, `AuditExtended`); the
//! enum is `#[non_exhaustive]` so a future variant landing in the authz
//! crate without a corresponding match arm here would simply not be
//! generated by the strategy — the tests stay green and the
//! same-property check survives the upgrade. The unknown-variant path
//! is exercised by `obligation_static_reason_audit.rs` and is out of
//! scope for the composition invariants.

use std::collections::BTreeSet;
use std::time::SystemTime;

use bytes::Bytes;
use proptest::prelude::*;
use rustgate_authz::Obligation;
use rustgate_core::identity::Identity;
use rustgate_core::message::{Destination, MessageType, Metadata, RoutableMessage};
use rustgate_router::obligations::{UnknownObligationPolicy, apply_obligations};

// ── Payload corpus ──────────────────────────────────────────────────────
//
// The dispatcher's MaskPoint actuator branches on the first
// non-whitespace byte of the payload (`<` → XML-intent → parse / mask
// or fail-closed; otherwise → forward unmodified). We exercise both
// branches so the proptest covers the parse path *and* the binary
// pass-through path.

/// Well-formed CoT event with masked-coordinate point. Drives the
/// `quick_xml`-based `<point>` rewrite path.
const COT_WITH_POINT: &[u8] = br#"<event uid="u1" type="a-f-G-U-C" start="2024-01-01T00:00:00Z" stale="2024-01-01T00:05:00Z"><point lat="38.8977" lon="-77.0365" hae="125.4"/></event>"#;

/// Well-formed CoT chat event without a `<point>` element. The masker
/// short-circuits via the start-element filter so this exercises the
/// "XML-intent, no point to mask" code path.
const COT_CHAT: &[u8] =
    br#"<event uid="c1" type="b-t-f"><detail><__chat>hello</__chat></detail></event>"#;

/// Binary payload with first byte = `0xFD` (MAVLink v2 magic). Drives
/// the non-XML pass-through branch so the proptest covers both arms of
/// the MaskPoint dispatch fan-out.
const BINARY_FRAME: &[u8] = &[0xFD, 0x09, 0x00, 0x00, 0x00, 0x01, 0x01, 0x02, 0x03];

/// Empty payload — equivalent to the post-MaskPayload terminal state.
/// Re-applying any further obligation must be a no-op.
const EMPTY: &[u8] = b"";

fn payload_strategy() -> impl Strategy<Value = &'static [u8]> {
    prop_oneof![
        Just(COT_WITH_POINT),
        Just(COT_CHAT),
        Just(BINARY_FRAME),
        Just(EMPTY),
    ]
}

/// Strategy producing one of the known obligation variants. The
/// authz crate's [`Obligation`] enum is `#[non_exhaustive]`, but only
/// known variants can be constructed from outside the defining crate —
/// which is exactly what the proptest needs (the dispatcher's
/// composition invariants are stated over known variants only; the
/// unknown-variant path is its own audit-rate-limit contract pinned
/// elsewhere). Refs #857 added three CDI variants (`StripPii`,
/// `DegradePosition`, `InjectMarking`) that participate in the
/// composition invariants alongside the original four.
fn obligation_strategy() -> impl Strategy<Value = Obligation> {
    prop_oneof![
        Just(Obligation::MaskPoint),
        Just(Obligation::MaskPayload),
        Just(Obligation::TagClassified),
        Just(Obligation::AuditExtended),
        // Refs #857 — cross-domain inspection scaffold variants.
        Just(Obligation::StripPii),
        Just(Obligation::DegradePosition {
            precision_meters: 1000,
        }),
        Just(Obligation::InjectMarking {
            marking: "//SECRET//NOFORN".to_string(),
        }),
    ]
}

/// Small obligation sets (0..=4 elements). The composition properties
/// scale linearly in the set size; covering up to four obligations is
/// enough to exercise every permutation across the four known variants
/// while keeping the proptest's case count bounded.
fn obligation_set_strategy() -> impl Strategy<Value = Vec<Obligation>> {
    prop::collection::vec(obligation_strategy(), 0..=4)
}

fn message_strategy() -> impl Strategy<Value = RoutableMessage> {
    payload_strategy().prop_map(|payload| {
        let id =
            Identity::new("alice".into(), "abc123".into(), BTreeSet::new()).expect("test identity");
        RoutableMessage {
            source: id,
            destination: Destination::Broadcast,
            payload: Bytes::from_static(payload),
            metadata: Metadata::new(SystemTime::UNIX_EPOCH, "cot".into(), MessageType::Position),
            entity: None,
        }
    })
}

/// Apply `obligations` under the default fail-closed policy. All
/// strategy-produced obligations are known variants so the call always
/// returns `Ok(())` — we unwrap to keep the proptest bodies focussed on
/// the composition invariants.
fn apply(msg: &mut RoutableMessage, obligations: &[Obligation]) {
    apply_obligations(msg, obligations, UnknownObligationPolicy::FailClosed)
        .expect("known obligations always apply under FailClosed");
}

proptest! {
    /// **Composition equivalence** — applying `A` then `B` separately
    /// to the same starting message produces a payload byte-identical
    /// to applying `A ∪ B` in one shot. This is the property that lets
    /// the per-recipient fan-out stack Send-then-Receive obligations on
    /// a per-recipient copy without having to re-derive the canonical
    /// chaining order at every call site (refs #882, #787).
    ///
    /// The post-state `message_type` must also match: `MaskPayload`
    /// coerces it to `Other("masked")` and a regression that applied
    /// the coercion on only one of the two paths would surface here as
    /// a `Position` vs `Other("masked")` divergence.
    #[test]
    fn applying_a_then_b_equals_applying_a_union_b(
        msg in message_strategy(),
        a in obligation_set_strategy(),
        b in obligation_set_strategy(),
    ) {
        let combined: Vec<Obligation> = a.iter().chain(b.iter()).cloned().collect();

        let mut staged = msg.clone();
        apply(&mut staged, &a);
        apply(&mut staged, &b);

        let mut one_shot = msg;
        apply(&mut one_shot, &combined);

        prop_assert_eq!(
            staged.payload, one_shot.payload,
            "staged a→b payload must match one-shot a∪b"
        );
        prop_assert_eq!(
            staged.metadata.message_type, one_shot.metadata.message_type,
            "staged a→b message_type must match one-shot a∪b"
        );
    }

    /// **Idempotence** — applying the same obligation set twice produces
    /// the same payload as applying it once. The drain path can re-run
    /// obligation application on a stored copy if a transient delivery
    /// failure forces a retry; without this property the second
    /// application could drift the payload further (e.g. a hypothetical
    /// future obligation that appended a marker on every call).
    #[test]
    fn double_application_is_idempotent(
        msg in message_strategy(),
        obligations in obligation_set_strategy(),
    ) {
        let mut once = msg;
        apply(&mut once, &obligations);
        let snapshot = once.clone();

        let mut twice = once;
        apply(&mut twice, &obligations);

        prop_assert_eq!(
            twice.payload, snapshot.payload,
            "second application of the same obligation set must not drift the payload"
        );
        prop_assert_eq!(
            twice.metadata.message_type, snapshot.metadata.message_type,
            "second application of the same obligation set must not drift message_type"
        );
    }

    /// **Order independence** — two permutations of the same obligation
    /// set produce byte-identical post-PEP output. The dispatcher
    /// enforces this via a stable sort on
    /// [`Obligation::chain_sort_key`] before actuation; without it, a
    /// callsite that emitted `[MaskPayload, MaskPoint]` versus
    /// `[MaskPoint, MaskPayload]` would race and produce non-deterministic
    /// audit / dedup state across recipients (refs #882).
    ///
    /// This property is asserted across the **full** known-variant
    /// strategy — the dispatcher's stable sort must hold for every
    /// pair, not just the redactor pairs.
    #[test]
    fn order_independence_for_known_obligations(
        msg in message_strategy(),
        a in obligation_strategy(),
        b in obligation_strategy(),
    ) {
        let mut ab = msg.clone();
        apply(&mut ab, &[a.clone(), b.clone()]);

        let mut ba = msg;
        apply(&mut ba, &[b, a]);

        prop_assert_eq!(
            ab.payload, ba.payload,
            "permutation [a, b] vs [b, a] must produce identical payloads"
        );
        prop_assert_eq!(
            ab.metadata.message_type, ba.metadata.message_type,
            "permutation [a, b] vs [b, a] must produce identical message_type"
        );
    }

    /// **Set-equivalence under permutation** — two arbitrary
    /// permutations of the *same multiset* of obligations produce
    /// byte-identical post-PEP output. Covers permutations larger than
    /// the pairwise case above (sets of up to 4 elements) so a
    /// regression that only manifested at length 3+ would surface here.
    #[test]
    fn permutation_independence_for_obligation_sets(
        msg in message_strategy(),
        obligations in obligation_set_strategy(),
        // Use a small u64 seed to permute the obligation set — proptest
        // shrinks the seed independently of the obligation list, giving
        // a useful counter-example if a regression turns up.
        permute_seed in any::<u64>(),
    ) {
        let mut permuted = obligations.clone();
        // Deterministic permutation driven by `permute_seed`. A simple
        // index-rotation by `permute_seed % len` is enough to cover the
        // "input order varies" axis without adding a fresh rand dev-dep.
        // Casting `permute_seed` to `usize` is safe under the modulus —
        // we only ever care about the low bits relative to `len`.
        if !permuted.is_empty() {
            let rot = usize::try_from(permute_seed % permuted.len() as u64)
                .expect("modulus by len fits in usize");
            permuted.rotate_left(rot);
        }

        let mut original = msg.clone();
        apply(&mut original, &obligations);

        let mut rotated = msg;
        apply(&mut rotated, &permuted);

        prop_assert_eq!(
            original.payload, rotated.payload,
            "rotation of obligation list must not change the post-PEP payload"
        );
        prop_assert_eq!(
            original.metadata.message_type, rotated.metadata.message_type,
            "rotation of obligation list must not change message_type"
        );
    }
}
